"""Run long demonstration worlds and write a Markdown report of what emerged.

    python scripts/demo_report.py --out docs/DEMO_RESULTS.md
"""
import argparse
import json
import time

import numpy as np

from genesis import Simulation, WorldConfig
from genesis.analytics.experiments import compare_frameworks


def run(label, cfg, ticks, lines):
    sim = Simulation(cfg)
    t0 = time.time()
    lines.append(f"## {label}\n")
    lines.append(f"`seed={cfg.seed}, scenario={cfg.scenario}, initial_population={cfg.initial_population}, "
                 f"{cfg.width}x{cfg.height} cells, {ticks} virtual hours = {ticks / cfg.year_ticks:.1f} years`\n")
    lines.append("| virtual time | population | species | max generation | mean brain | groups | settlements | polities | skills held by >10% |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    step = max(1, ticks // 10)
    while sim.clock.tick < ticks:
        sim.run(step)
        r = sim.analytics.series[-1]
        if not len(sim.pop):
            lines.append(f"| {sim.clock.info()['label']} | **extinct** | | | | | | | |")
            break
        sk = ", ".join(k for k, v in r.get("skills", {}).items() if v > 0.1) or "—"
        lines.append(f"| {sim.clock.info()['label']} | {r['population']} | {r['species']} | {r.get('max_generation')} | "
                     f"{r['traits']['brain']:.3f} | {r['groups']} | {r['settlements']} | {json.dumps(r['polities'])} | {sk} |")
    lines.append(f"\nWall-clock: {time.time() - t0:.0f} s ({1000 * (time.time() - t0) / max(1, sim.clock.tick):.1f} ms per virtual hour).\n")
    lines.append("**Emergent firsts** (nothing below was scripted; each was detected when it first happened):\n")
    for f in sorted(sim.analytics.firsts.values(), key=lambda f: f["tick"]):
        lines.append(f"- t={f['tick']} ({f['date']}): {f['text']}")
    causes = sim.history.death_causes()
    tot = sum(causes.values())
    lines.append(f"\n**Causes of death** ({tot} deaths, {sim.history.counts()['dead_without_cause']} without a cause): " +
                 ", ".join(f"{k} {100 * v / tot:.0f}%" for k, v in sorted(causes.items(), key=lambda kv: -kv[1])))
    lines.append(f"\n**Reality layers known to inhabitants:** {', '.join(sorted(sim.civ.layers))}\n")
    if sim.analytics.series:
        first, last = sim.analytics.series[0], sim.analytics.series[-1]
        if "traits" in first and "traits" in last:
            lines.append("**Trait change (population mean, start → end):** " + ", ".join(
                f"{k} {first['traits'][k]:.2f}→{last['traits'][k]:.2f}" for k in ("size", "brain", "speed", "sociality", "communication", "diet", "lifespan")))
    groups = sorted([g for g in sim.civ.groups.values() if g["dissolved"] is None], key=lambda g: -g.get("size", 0))[:3]
    for g in groups:
        vocab = ", ".join(f"{c.replace('plant:', '')}=“{v['word']}”" for c, v in list(g.get("vocabulary", {}).items())[:8])
        lines.append(f"\n- Group **{g['name']}** ({g['polity']}, {g['size']} members, language coherence {g.get('language_coherence')}): {vocab or 'no shared words'}")
    lines.append("")
    return sim


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/DEMO_RESULTS.md")
    ap.add_argument("--primordial-ticks", type=int, default=20000)
    ap.add_argument("--advanced-ticks", type=int, default=15000)
    ap.add_argument("--compare-ticks", type=int, default=3000)
    a = ap.parse_args()
    lines = ["# GENESIS — demonstration results\n",
             "Generated by `scripts/demo_report.py`. Every number below comes from an actual run; rerunning with the same seeds reproduces it exactly.\n"]
    run("World A — primordial start (stages 1–3)", WorldConfig(seed=1, record_events=True), a.primordial_ticks, lines)
    run("World B — advanced start (stages 4–8)", WorldConfig(seed=2, scenario="advanced", initial_population=250), a.advanced_ticks, lines)
    lines.append("## Moral-education experiment\n")
    lines.append(f"Same planet and founders (advanced scenario, seeds 1–2, {a.compare_ticks} h each), different educational ideals.\n")
    res = compare_frameworks(("none", "quran_inspired", "utilitarian", "kin_loyalty", "egoist"), (1, 2), a.compare_ticks)
    keys = ["final_population", "mean_population", "violent_death_share", "starvation_share", "sharing_per_1000h", "trades", "rituals"]
    lines.append("| framework | " + " | ".join(keys) + " |")
    lines.append("|---" * (len(keys) + 1) + "|")
    for r in res:
        lines.append(f"| {r['framework']} | " + " | ".join(str(r[k]) for k in keys) + " |")
    lines.append("\nTwo seeds per arm is a small sample; differences of a few percent are within run-to-run noise. "
                 "The experiment shows the mechanism works and is measurable, not a verdict on any ethical tradition.\n")
    open(a.out, "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
